import re

ROOT = Path(__file__).resolve().parents[1]
CODE_EXTENSIONS = {'.py', '.js', '.jsx', '.html', '.css'}
PRIVATE_PREFIXES = ('outputs/', 'backups/', 'media/', 'instance/', 'staticfiles/', 'frontend_build/', '.codex-attachments/', '.codex-remote-attachments/')


def source_path(root, name):
    path = (root / name).resolve()
    if Path(name).is_absolute() or name.startswith(PRIVATE_PREFIXES) or name == '.env' or not path.is_relative_to(root.resolve()) or not path.is_file():
        raise ValueError('Unsafe or missing source file: ' + name)
    return path


def symbols_in(path):
    text = path.read_text(encoding='utf-8-sig')
    if path.suffix != '.py':
        return lambda name: bool(re.search(r'\b' + re.escape(name) + r'\b', text))
    names = set()
    def visit(nodes, prefix=''):
        for node in nodes:
            if isinstance(node, (ast.ClassDef, ast.FunctionDef, ast.AsyncFunctionDef)):
                names.add(prefix + node.name)
                visit(node.body, prefix + node.name + '.')
            elif isinstance(node, (ast.Import, ast.ImportFrom)):
                names.update(a.asname or a.name for a in node.names)
            elif isinstance(node, (ast.Assign, ast.AnnAssign)):
                for target in node.targets if isinstance(node, ast.Assign) else [node.target]:
                    if isinstance(target, ast.Name): names.add(prefix + target.id)
    visit(ast.parse(text).body)
    return names.__contains__


def load_registry(root=ROOT, path=None):
    root = Path(root).resolve()
    data = json.loads(Path(path or root / 'docs/component-map.json').read_text(encoding='utf-8-sig'))
    components = data['components']
    ids = [c['id'] for c in components]
    if len(ids) != len(set(ids)) or any(not re.fullmatch(r'[a-z][a-z0-9-]*', key) for key in ids):
        raise ValueError('Component IDs must be unique lowercase identifiers')
    lookup = {c['id']: c for c in components}
    mapped = set()
    for component in components:
        seen = {component['id']}
        parent = component.get('parent')
        while parent:
            if parent not in lookup or parent in seen: raise ValueError('Invalid parent or cycle: ' + component['id'])
            seen.add(parent); parent = lookup[parent].get('parent')
        for file in component['files']:
            source = source_path(root, file['path']); mapped.add(file['path'])
            has_symbol = symbols_in(source) if file.get('symbols') else None
            for symbol in file.get('symbols', []):
                if not has_symbol(symbol): raise ValueError('Missing symbol: ' + file['path'] + ': ' + symbol)
        for test in component.get('tests', []): source_path(root, test); mapped.add(test)
    for recipe in data['recipes']:
        if not set(recipe['components']).issubset(lookup): raise ValueError('Unknown recipe component')
    code = set()
    for folder in data.get('inventory_roots', []):
        directory = (root / folder).resolve()
        if not directory.is_relative_to(root): raise ValueError('Unsafe inventory root')
        for file in directory.rglob('*'):
            if file.is_file() and file.suffix in CODE_EXTENSIONS and '__pycache__' not in file.parts:
                code.add(file.relative_to(root).as_posix())
    if code - mapped: raise ValueError('Unmapped source files: ' + ', '.join(sorted(code - mapped)))
    return data


def tree_lines(data):
    def children(parent, depth):
        for c in data['components']:
            if c.get('parent') == parent:
                yield '  ' * depth + '- [' + c['title'] + '](#' + c['id'] + ')'
                yield from children(c['id'], depth + 1)
    return list(children(None, 0))


def render_markdown(data):
    lines = ['<!-- Generated by scripts/build_component_map.py; edit component-map.json. -->', '# ' + data['title'], '', data['intro'], '', 'Run `python scripts/build_component_map.py` after editing the registry; use `--check` before publishing.', '', '## Component tree', '', *tree_lines(data), '', '## I want to change…', '']
    for recipe in data['recipes']:
        lines += ['### ' + recipe['title'], '', *[str(i + 1) + '. ' + step for i, step in enumerate(recipe['steps'])], '', 'Related: ' + ', '.join('[' + key + '](#' + key + ')' for key in recipe['components']) + '.', '']
    for c in data['components']:
        lines += ['<a id="' + c['id'] + '"></a>', '## ' + c['title'], '', c['purpose'], '', '| File | Named parts | What to change here |', '| --- | --- | --- |']
        for f in c['files']:
            lines.append('| [' + f['path'] + '](../' + f['path'] + ') | ' + ', '.join('`' + n + '`' for n in f.get('symbols', [])) + ' | ' + f['role'].replace('|', '\\|') + ' |')
        lines += ['', '**Settings first:** ' + c['settings'], '', '**Keep in mind:** ' + c['caution'], '']
        if c.get('tests'): lines += ['**Verify:** ' + ', '.join('[' + p + '](../' + p + ')' for p in c['tests']) + '.', '']
    return '\n'.join(lines).rstrip() + '\n'


