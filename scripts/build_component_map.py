def render_html(data):
    e = html.escape
    roots = [c for c in data['components'] if not c.get('parent')]
    nav = ''.join('<li><a href="#' + c['id'] + '">' + e(c['title']) + '</a></li>' for c in roots)
    recipes = ''.join('<h3>' + e(r['title']) + '</h3><ol>' + ''.join('<li>' + e(s) + '</li>' for s in r['steps']) + '</ol><p>' + ' · '.join('<a href="#' + key + '">' + e(key) + '</a>' for key in r['components']) + '</p>' for r in data['recipes'])
    cards = []
    for c in data['components']:
        files = ''.join('<div class="file"><a href="../' + e(f['path'], quote=True) + '">' + e(f['path']) + '</a><p>' + e(f['role']) + '</p><p>' + ' '.join('<code>' + e(n) + '</code>' for n in f.get('symbols', [])) + '</p></div>' for f in c['files'])
        tests = ', '.join('<a href="../' + e(p, quote=True) + '">' + e(p) + '</a>' for p in c.get('tests', [])) or 'Use the related feature checks.'
        parent = '<p>Inside <a href="#' + c['parent'] + '">' + e(c['parent']) + '</a></p>' if c.get('parent') else ''
        cards.append('<details open id="' + c['id'] + '"><summary>' + e(c['title']) + '</summary>' + parent + '<p>' + e(c['purpose']) + '</p>' + files + '<p><strong>Settings first:</strong> ' + e(c['settings']) + '</p><p><strong>Keep in mind:</strong> ' + e(c['caution']) + '</p><p><strong>Verify:</strong> ' + tests + '</p></details>')
    return '<!doctype html>\n<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>' + e(data['title']) + '</title><style>' + STYLE + '</style></head><body><header><h1>' + e(data['title']) + '</h1><p>' + e(data['intro']) + '</p><p><a href="COMPONENT-MAP.md">Markdown version</a> · <a href="DEVELOPMENT.md">Developer guide</a></p><p>Edit component-map.json, then run python scripts/build_component_map.py. Source links open relative to this downloaded repository; open the displayed paths in your editor to modify code.</p></header><div class="layout"><nav aria-label="Component groups"><strong>Find your area</strong><ul>' + nav + '</ul></nav><main><label for="search">Search components, files or named parts</label><input type="search" id="search" placeholder="Try: invoice, logo, payment, password"><p id="count" role="status">' + str(len(cards)) + ' components</p><section class="recipes" aria-label="Common changes"><h2>I want to change…</h2>' + recipes + '</section>' + ''.join(cards) + '</main></div><script>' + SCRIPT + '</script></body></html>\n'


def generate(root=ROOT, registry=None, check=False):
    root = Path(root); data = load_registry(root, registry)
    outputs = {'COMPONENT-MAP.md': render_markdown(data), 'component-map.html': render_html(data)}
    valid = True
    for name, content in outputs.items():
        path = root / 'docs' / name
        if check:
            if not path.exists() or path.read_text(encoding='utf-8') != content:
                print('Stale component guide: ' + str(path)); valid = False
        else: path.write_text(content, encoding='utf-8')
    return valid


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Validate coverage/references and fail on stale generated guides.')
    args = parser.parse_args()
    try:
        ok = generate(check=args.check)
    except (ValueError, KeyError, OSError) as error:
        parser.exit(1, str(error) + '\n')
    raise SystemExit(0 if ok else 1)
